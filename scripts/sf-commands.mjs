#!/usr/bin/env node
// @ts-check
// Regenerates lib/sf-commands.mjs, the guard's list of sf command ids, from the oclif manifests
// of an installed Salesforce CLI. It only reads JSON files; it never runs sf.
// Usage: node scripts/sf-commands.mjs [/usr/local/lib/node_modules/@salesforce/cli]
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const root = process.argv[2] ?? '/usr/local/lib/node_modules/@salesforce/cli';
const files = [path.join(root, 'oclif.manifest.json')];
for (const scope of ['@salesforce', '@oclif']) {
  const dir = path.join(root, 'node_modules', scope);
  for (const name of fs.existsSync(dir) ? fs.readdirSync(dir) : []) {
    const f = path.join(dir, name, 'oclif.manifest.json');
    if (fs.existsSync(f)) files.push(f);
  }
}
/** @type {Map<string, boolean>} */ const ids = new Map();
for (const f of files) {
  for (const c of Object.values(JSON.parse(fs.readFileSync(f, 'utf8')).commands ?? {})) {
    const takesArgs = c.strict === false || Object.keys(c.args ?? {}).length > 0;
    for (const id of [c.id, ...(c.aliases ?? []), ...(c.hiddenAliases ?? [])]) ids.set(id.replaceAll(' ', ':'), takesArgs);
  }
}
const version = JSON.parse(fs.readFileSync(path.join(root, 'package.json'), 'utf8')).version;
const lines = [...ids].sort(([a], [b]) => a.localeCompare(b)).map(([id, args]) => `  '${id}${args ? '*' : ''}',`);
const out = `// @ts-check
// Generated by scripts/sf-commands.mjs from @salesforce/cli ${version} (${files.length} manifests). Do not edit.
// Every sf command id and alias; a trailing * marks a command that takes positional arguments.
export const SF_COMMAND_IDS = [
${lines.join('\n')}
];
`;
fs.writeFileSync(path.join(path.dirname(fileURLToPath(import.meta.url)), '..', 'lib', 'sf-commands.mjs'), out);
console.log(`${ids.size} ids from ${files.length} manifests`);
